"""Turns findings into the deliverable: a plain-English, HIPAA-mapped Markdown
report, modeled on a consultant's executive summary -- worst gaps first, each one
explained so a non-technical practice manager can act on it."""

from __future__ import annotations

from datetime import datetime, timezone

from .engine import AssessmentResult
from .findings import Severity

_SEVERITY_ICON = {
    Severity.CRITICAL: "🔴",
    Severity.HIGH: "🟠",
    Severity.MEDIUM: "🟡",
    Severity.LOW: "🔵",
    Severity.INFO: "⚪",
}


def render_markdown(result: AssessmentResult) -> str:
    lines: list[str] = []
    counts = result.counts_by_severity()
    ranked = result.ranked()

    # ---- header -------------------------------------------------------------
    lines += [
        f"# Security Posture Assessment — {result.practice_name}",
        "",
        "> Generated by **Perikrone** — read-only assessment, "
        "nothing in your environment was changed.",
        "",
        f"- **Data source:** {result.source}",
        f"- **Accounts reviewed:** {result.user_count}",
        f"- **Assessed:** {result.collected_at or _now()}",
        f"- **Total findings:** {len(result.findings)}",
        "",
    ]

    # ---- executive summary --------------------------------------------------
    lines += ["## Executive summary", ""]
    if result.clean:
        lines += [
            "No gaps were found against the five Phase-1 checks. Keep verifying "
            "on a regular schedule — posture drifts as staff and settings change.",
            "",
        ]
    else:
        headline = (
            counts[Severity.CRITICAL] and "immediate action is required"
            or counts[Severity.HIGH] and "there are serious gaps to close"
            or "there are gaps worth addressing"
        )
        lines += [
            f"This assessment found **{len(result.findings)} issue(s)**, and "
            f"{headline}. The table below counts them by urgency; each is "
            "detailed afterward, worst first, with the HIPAA rule it affects and "
            "how to fix it.",
            "",
            "| Severity | Count |",
            "|---|---|",
        ]
        for sev in sorted(Severity, reverse=True):
            if counts[sev]:
                lines.append(f"| {_SEVERITY_ICON[sev]} {sev.label} | {counts[sev]} |")
        lines.append("")

    # ---- findings -----------------------------------------------------------
    if ranked:
        lines += ["## Findings", ""]
        for i, f in enumerate(ranked, 1):
            lines += [
                f"### {i}. {_SEVERITY_ICON[f.severity]} {f.title} "
                f"— _{f.severity.label}_",
                "",
                f"**What we found:** {f.summary}",
                "",
                f.detail,
                "",
            ]
            if f.affected:
                lines.append("**Affected:**")
                lines += [f"- {a}" for a in f.affected]
                lines.append("")
            if f.hipaa:
                lines.append("**HIPAA controls affected:**")
                lines += [f"- {c}" for c in f.hipaa]
                lines.append("")
            if f.fix:
                lines.append("**How to fix it:**")
                lines += [f"{n}. {step}" for n, step in enumerate(f.fix, 1)]
                lines.append("")

    # ---- footer -------------------------------------------------------------
    lines += [
        "---",
        "",
        "_Perikrone is an assessment tool: it reads configuration only and never "
        "changes, writes to, or accesses patient data in any system. This report "
        "supports, but does not replace, a full HIPAA Security Rule risk analysis "
        "under 45 CFR 164.308(a)(1)(ii)(A)._",
        "",
    ]
    return "\n".join(lines)


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
